"""
seed_data.py
All 131 WBTC (West Bengal Transport Corporation) intra-city bus routes,
covering Kolkata, Howrah, Salt Lake, New Town, and North/South 24 Parganas.

DATA PROVENANCE
----------------
Route numbers, originating/terminating points, and the full ordered
stoppage list for every route below are transcribed verbatim from WBTC's
own published "WBTC City Bus Routes" table at
https://wbtconline.in/wbtc-city-bus-routes (131 routes, also cross-checked
against the linked PDF "INTRA_CITY_RTS_Latest-small.pdf"). This is the
authoritative, official route topology.

WHAT IS STILL NOT OFFICIAL DATA (read before using for real commuting):
- WBTC does NOT publish stop-level GPS coordinates or a timetable/headway
  for these intra-city routes (only for its long-distance AC coach
  bookings). So, in the STOPS table below:
    * `verified=True` coordinates are real, manually geocoded landmark
      positions for ~110 well-known stops (Esplanade, Howrah Station,
      Barasat, Salt Lake Karunamoyee, etc.).
    * `verified=False` coordinates are LINEARLY INTERPOLATED along each
      route between the nearest verified landmarks on either side, purely
      so every stop has *some* plausible map position. These are NOT
      geocoded and can be meaningfully wrong for small lanes/crossings -
      replace them with real geocoding (e.g. a geocoding API pass, or a
      field survey) before using this for navigation or ETAs.
- `offset_minutes` in each route's stop list, and every route's
  `headway_min`/`first`/`last` service-window fields, are illustrative
  placeholders (even 3-minutes-per-stop spacing, a flat 20-min headway,
  06:00-21:00 window) for demo/testing purposes only - WBTC does not
  publish this level of schedule detail for intra-city routes, and there
  is still no official public real-time API or open GTFS feed for WBTC.

One more source quirk to be aware of: WBTC's table lists a separate
"Originating Point" / "Terminating Point" plus a free-text "Stoppage"
list, and for a handful of routes the stoppage text is written in the
opposite direction to (or loops back past) the origin/terminus columns.
This script preserves that as published rather than silently
"correcting" it, so a few routes below show the origin or terminus
appearing twice in the stop sequence - treat those as a single loop
point, not a data-entry bug on our end.

Replace/extend the coordinates and timing fields with a genuine field
survey, an RTI/official data release, or a licensed live-position feed
before relying on this for real commuting decisions. See README.md for
notes on plugging in a live feed if/when one becomes available.
"""

